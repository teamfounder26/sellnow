type Ctx = { db: DB; workspaceId: string; userId: string; locale: "ms" | "en" };

export const CREATIVE_TYPES = ["ad_copy", "campaign_headline", "product_description", "video_script", "voiceover_script", "poster", "social_graphic", "photo_enhance", "storyboard"] as const;
/** Text types are generated by the configured LLM; visual types need an image provider (not configured yet). */
export const TEXT_CREATIVE_TYPES = ["ad_copy", "campaign_headline", "product_description", "video_script", "voiceover_script"] as const;
export const OBJECTIVES = ["awareness", "benefits", "problem_solution", "offer", "features", "education", "lead_generation", "conversion"] as const;
export const RATIOS = ["1:1", "4:5", "9:16", "16:9"] as const;

export function imageProviderConfigured() {
  return imageGenerationConfigured(); // OpenAI-compatible image adapter (IMAGE_API_KEY) — see lib/ai/image.ts.
}

export const creativeRequestSchema = z.object({
  productId: z.string(),
  type: z.enum(TEXT_CREATIVE_TYPES),
  objective: z.enum(OBJECTIVES),
  style: z.string().max(80).default("friendly"),
  ratio: z.enum(RATIOS).optional(),
});

export async function generateTextCreative(ctx: Ctx, raw: z.input<typeof creativeRequestSchema>) {
  const req = creativeRequestSchema.parse(raw);
  const p = await ctx.db.query.products.findFirst({ where: and(eq(products.id, req.productId), eq(products.workspaceId, ctx.workspaceId)) });
  if (!p) throw new AppError("errors.notFound");
  const profile = await ctx.db.query.businessProfiles.findFirst({ where: eq(businessProfiles.workspaceId, ctx.workspaceId) });
  const confirmed = Object.entries(profile?.fields ?? {})
    .filter(([, f]) => f.status === "confirmed" && f.value != null)
    .map(([k, f]) => `${k}: ${k === "price" ? `RM${(Number(f.value) / 100).toFixed(2)}` : f.value}`)
    .join("\n");
  const { data, generationId } = await runGeneration(ctx.db, {
    workspaceId: ctx.workspaceId,
    userId: ctx.userId,
    task: "creative.text",
    input: req,
    request: {
      system: creativeSystem(ctx.locale),
      schema: creativeTextSchema,
      prompt: `Creative type: ${req.type}\nObjective: ${req.objective}\nStyle: ${req.style}\n${req.ratio ? `Placement ratio: ${req.ratio}\n` : ""}Product: ${p.name}\nPrice: RM${(p.priceSen / 100).toFixed(2)}\nDescription: ${p.description}\nConfirmed business facts:\n${confirmed}`,
    },
  });
  const id = newId("crt");
  await ctx.db.insert(creatives).values({
    id,
    workspaceId: ctx.workspaceId,
    productId: p.id,
    type: req.type,
    objective: req.objective,
    ratio: req.ratio ?? null,
    content: data as unknown as Record<string, unknown>,
    priceSnapshotSen: p.priceSen,
    generationId,
  });
  await track(ctx.db, "creative_generated", { workspaceId: ctx.workspaceId, props: { type: req.type } });
  return id;
}

export async function listCreatives(db: DB, workspaceId: string) {
  return db.query.creatives.findMany({ where: eq(creatives.workspaceId, workspaceId), orderBy: desc(creatives.createdAt), limit: 100 });
}

export async function setCreativeStatus(db: DB, ctx: { workspaceId: string; userId: string }, id: string, status: "draft" | "approved") {
  const r = await db.update(creatives).set({ status }).where(and(eq(creatives.id, id), eq(creatives.workspaceId, ctx.workspaceId))).returning();
  if (!r.length) throw new AppError("errors.notFound");
  await audit(db, { workspaceId: ctx.workspaceId, actorUserId: ctx.userId, action: `creative.${status}`, entity: "creative", entityId: id });
  // Creative Star: first saved creative that came from a SUCCESSFUL generation and was approved by the seller.
  const c = r[0]!;
  if (status === "approved" && c.generationId && Object.keys(c.content).length > 0) {
    await unlock(db, ctx.workspaceId, "creative_star", 1, { type: "creative", id: c.id });
  }
}

// ---------------------------------------------------------------- Campaigns
export const campaignSchema = z.object({
  name: z.string().trim().min(3).max(120),
  productId: z.string(),
  creativeId: z.string().optional().nullable(),
  objective: z.enum(["awareness", "traffic", "leads", "sales"]),
  audience: z.object({ location: z.string().max(120).default("Malaysia"), ageMin: z.number().int().min(18).max(65), ageMax: z.number().int().min(18).max(65), interests: z.string().max(300).default("") }),
  dailyBudget: z.string().transform((v, c) => {
    const sen = parseRinggitToSen(v);
    if (sen === null || sen < 500) {
      c.addIssue({ code: "custom", message: "marketing.minBudget" });
      return z.NEVER;
    }
    return sen;
  }),
  durationDays: z.number().int().min(1).max(90),
});

export async function metaStatus(db: DB, workspaceId: string) {
  const appConfigured = Boolean(process.env.META_APP_ID && process.env.META_APP_SECRET);
  const row = await db.query.integrations.findFirst({ where: and(eq(integrations.workspaceId, workspaceId), eq(integrations.provider, "meta")) });
  return { appConfigured, connected: row?.status === "connected" };
}

export async function createCampaignDraft(db: DB, ctx: { workspaceId: string; userId: string }, raw: z.input<typeof campaignSchema>) {
  const c = campaignSchema.parse(raw);
  if (c.audience.ageMin > c.audience.ageMax) throw new AppError("marketing.badAge");
  const p = await db.query.products.findFirst({ where: and(eq(products.id, c.productId), eq(products.workspaceId, ctx.workspaceId)) });
  if (!p) throw new AppError("errors.notFound");
  if (c.creativeId) {
    const cr = await db.query.creatives.findFirst({ where: and(eq(creatives.id, c.creativeId), eq(creatives.workspaceId, ctx.workspaceId)) });
    if (!cr) throw new AppError("errors.notFound");
  }
  const id = newId("cmp");
  await db.insert(campaigns).values({
    id,
    workspaceId: ctx.workspaceId,
    productId: c.productId,
    creativeId: c.creativeId ?? null,
    name: c.name,
    objective: c.objective,
    audience: c.audience,
    dailyBudgetSen: c.dailyBudget,
    durationDays: c.durationDays,
  });
  await audit(db, { workspaceId: ctx.workspaceId, actorUserId: ctx.userId, action: "campaign.drafted", entity: "campaign", entityId: id });
  await track(db, "campaign_created", { workspaceId: ctx.workspaceId });
  return id;
}

/** Changing budget always clears approval — budgets are never altered silently. */
export async function updateCampaignBudget(db: DB, ctx: { workspaceId: string; userId: string }, id: string, dailyBudget: string) {
  const sen = parseRinggitToSen(dailyBudget);
  if (sen === null || sen < 500) throw new AppError("marketing.minBudget");
  const c = await db.query.campaigns.findFirst({ where: and(eq(campaigns.id, id), eq(campaigns.workspaceId, ctx.workspaceId)) });
  if (!c) throw new AppError("errors.notFound");
  if (c.status === "active" || c.status === "publishing") throw new AppError("marketing.liveBudgetChange");
  await db
    .update(campaigns)
    .set({ dailyBudgetSen: sen, status: "draft", approvedAt: null, approvedBy: null, approvedBudgetSen: null, updatedAt: new Date() })
    .where(eq(campaigns.id, id));
  await audit(db, { workspaceId: ctx.workspaceId, actorUserId: ctx.userId, action: "campaign.budget_changed", entity: "campaign", entityId: id, data: { fromSen: c.dailyBudgetSen, toSen: sen } });
}

export async function approveCampaign(db: DB, ctx: { workspaceId: string; userId: string }, id: string) {
  const c = await db.query.campaigns.findFirst({ where: and(eq(campaigns.id, id), eq(campaigns.workspaceId, ctx.workspaceId)) });
  if (!c) throw new AppError("errors.notFound");
  if (c.status !== "draft" && c.status !== "pending_approval") throw new AppError("marketing.notApprovable");
  await db
    .update(campaigns)
    .set({ status: "approved", approvedBy: ctx.userId, approvedAt: new Date(), approvedBudgetSen: c.dailyBudgetSen, updatedAt: new Date() })
    .where(eq(campaigns.id, id));
  await audit(db, { workspaceId: ctx.workspaceId, actorUserId: ctx.userId, action: "campaign.approved", entity: "campaign", entityId: id, data: { dailyBudgetSen: c.dailyBudgetSen, durationDays: c.durationDays } });
}

/** Publishing requires explicit approval for the exact budget AND a connected, authorized Meta account. */
export async function publishCampaign(db: DB, ctx: { workspaceId: string; userId: string }, id: string) {
  const c = await db.query.campaigns.findFirst({ where: and(eq(campaigns.id, id), eq(campaigns.workspaceId, ctx.workspaceId)) });
  if (!c) throw new AppError("errors.notFound");
  if (c.status !== "approved" || c.approvedBudgetSen !== c.dailyBudgetSen) throw new AppError("marketing.approvalRequired");
  const meta = await metaStatus(db, ctx.workspaceId);
  if (!meta.connected) throw new AppError("marketing.metaNotConnected");
  // A Meta Marketing API adapter is required here. Until it exists we refuse rather than simulate success.
  throw new AppError("marketing.metaAdapterMissing");
}

/**
 * Called ONLY by a provider adapter after the ad platform confirms the campaign was created and is
 * running (external id returned). This is the single place the Marketing Starter sticker is awarded;
 * drafts, approvals and failed launches never qualify.
 */
export async function recordCampaignLaunchConfirmed(db: DB, workspaceId: string, campaignId: string, externalId: string) {
  if (!externalId) throw new AppError("errors.validation");
  const r = await db
    .update(campaigns)
    .set({ status: "active", externalId, lastError: null, updatedAt: new Date() })
    .where(and(eq(campaigns.id, campaignId), eq(campaigns.workspaceId, workspaceId), eq(campaigns.status, "publishing")))
    .returning({ id: campaigns.id });
  if (!r.length) throw new AppError("marketing.notPublishing");
  await audit(db, { workspaceId, action: "campaign.launched", entity: "campaign", entityId: campaignId, data: { externalId } });
  await unlock(db, workspaceId, "marketing_starter", 1, { type: "campaign", id: campaignId });
}

export async function listCampaigns(db: DB, workspaceId: string) {
  return db.query.campaigns.findMany({ where: eq(campaigns.workspaceId, workspaceId), orderBy: desc(campaigns.createdAt) });
}
